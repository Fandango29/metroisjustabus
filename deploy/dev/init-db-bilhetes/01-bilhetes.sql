-- Estrutura da base de dados do serviço Bilhetes: tipos de bilhete e bilhetes
--
-- A base é criada pelo contentor bilhetes-db (variável POSTGRES_DB = BILHETES_DB_NAME).
-- Pode correr numa base que já tem dados: as tabelas só são criadas se não existirem
-- e os tipos iniciais não se duplicam (ON CONFLICT DO NOTHING).
-- O Postgres só corre este script ao criar o volume; numa base existente aplica-se à mão:
--   psql "$DATABASE_URL" -f 01-bilhetes.sql

-- Tipos de bilhete (RF-20, RF-21, A-01)
-- Preços em cêntimos inteiros. validade_tipo 'minutos' usa validade_minutos; 'mes_civil'
-- vale até ao fim do mês civil e não tem minutos (os meses têm 28 a 31 dias).
-- viagens vazio = ilimitadas durante a validade.
-- Os tipos nunca se apagam: desativam-se para novas vendas (ativo = FALSE, A-15).

CREATE TABLE IF NOT EXISTS tipos_bilhete (
    id               VARCHAR(20)  PRIMARY KEY,
    nome             VARCHAR(100) NOT NULL,
    preco_centimos   INTEGER      NOT NULL CHECK (preco_centimos > 0),
    validade_tipo    VARCHAR(20)  NOT NULL CHECK (validade_tipo IN ('minutos', 'mes_civil')),
    validade_minutos INTEGER      CHECK (validade_minutos > 0),
    viagens          INTEGER      CHECK (viagens > 0),
    condicoes        TEXT         NOT NULL,
    ativo            BOOLEAN      NOT NULL DEFAULT TRUE,
    criado_em        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    alterado_em      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    -- Igualdade de booleanos: um CHECK que dá NULL deixaria passar a linha.
    CHECK ((validade_tipo = 'minutos') = (validade_minutos IS NOT NULL))
);

-- Bilhetes comprados (RF-22 a RF-26, A-11)
-- passageiro_id é o identificador (sub) da conta no Keycloak.
-- preco_pago_centimos guarda o preço da compra: alterar o preço do tipo não o muda.
-- viagens_restantes vazio = ilimitadas. inicio_validade e fim_validade ficam vazios
-- até à primeira validação nos passes que começam nessa altura.
-- A chave de idempotência é única por passageiro (RF-23): a mesma chave do mesmo
-- passageiro não cria um segundo bilhete.

CREATE TABLE IF NOT EXISTS bilhetes (
    id                  INTEGER      GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              VARCHAR(64)  NOT NULL UNIQUE,
    tipo_id             VARCHAR(20)  NOT NULL REFERENCES tipos_bilhete(id),
    passageiro_id       VARCHAR(64)  NOT NULL,
    estado              VARCHAR(20)  NOT NULL DEFAULT 'emitido'
                        CHECK (estado IN ('emitido', 'ativo', 'esgotado', 'expirado')),
    viagens_restantes   INTEGER      CHECK (viagens_restantes >= 0),
    inicio_validade     TIMESTAMPTZ,
    fim_validade        TIMESTAMPTZ,
    preco_pago_centimos INTEGER      NOT NULL CHECK (preco_pago_centimos > 0),
    chave_idempotencia  VARCHAR(100) NOT NULL,
    comprado_em         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (passageiro_id, chave_idempotencia)
);

