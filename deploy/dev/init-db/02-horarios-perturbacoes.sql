-- Horários, viagens planeadas, perturbações e outbox (serviço Core)
--
-- Pode correr numa base que já tem dados: as tabelas só são criadas se não existirem
-- e os dados de exemplo não se duplicam (ON CONFLICT DO NOTHING).
-- O Postgres só corre este script ao criar o volume; numa base existente aplica-se à mão:
--   psql "$DATABASE_URL" -f 02-horarios-perturbacoes.sql

-- Tipos de dia e calendário de exceções (A-07)

CREATE TABLE IF NOT EXISTS tipos_dia (
    id   VARCHAR(20)  PRIMARY KEY,
    nome VARCHAR(100) NOT NULL
);

CREATE TABLE IF NOT EXISTS calendario_excecoes (
    data        DATE         PRIMARY KEY,
    tipo_dia_id VARCHAR(20)  NOT NULL REFERENCES tipos_dia(id),
    descricao   VARCHAR(200) NOT NULL
);

-- Viagens planeadas (A-05, A-15)
-- As horas são minutos desde o início do dia de serviço, para aceitar viagens
-- depois da meia-noite no mesmo dia de serviço: 24:30 = 1470 (A-17).
-- As viagens nunca se apagam: desativam-se (ativa = FALSE).

CREATE TABLE IF NOT EXISTS viagens (
    id          VARCHAR(20) PRIMARY KEY,
    linha_id    VARCHAR(10) NOT NULL REFERENCES linhas(id),
    tipo_dia_id VARCHAR(20) NOT NULL REFERENCES tipos_dia(id),
    partida_min INTEGER     NOT NULL CHECK (partida_min >= 0),
    capacidade  INTEGER     NOT NULL DEFAULT 80 CHECK (capacidade > 0),
    ativa       BOOLEAN     NOT NULL DEFAULT TRUE,
    UNIQUE (id, linha_id)
);

-- Hora prevista de cada viagem em cada paragem, pela ordem da linha.
-- A FK para linha_paragens garante que a ordem existe na linha da própria viagem.

CREATE TABLE IF NOT EXISTS viagem_horas (
    viagem_id VARCHAR(20) NOT NULL,
    linha_id  VARCHAR(10) NOT NULL,
    ordem     INTEGER     NOT NULL,
    minutos   INTEGER     NOT NULL CHECK (minutos >= 0),
    PRIMARY KEY (viagem_id, ordem),
    FOREIGN KEY (viagem_id, linha_id) REFERENCES viagens(id, linha_id),
    FOREIGN KEY (linha_id, ordem) REFERENCES linha_paragens(linha_id, ordem)
);

-- Perturbações
-- elemento_id aponta para uma linha, paragem ou viagem conforme o âmbito (sem FK por isso);
-- fica vazio quando o âmbito é 'periodo'. encerrada_em fica vazia enquanto a perturbação está ativa.

CREATE TABLE IF NOT EXISTS perturbacoes (
    id           INTEGER     GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo         VARCHAR(20) NOT NULL CHECK (tipo IN ('atraso', 'cancelamento', 'desvio', 'outro')),
    ambito       VARCHAR(20) NOT NULL CHECK (ambito IN ('linha', 'paragem', 'viagem', 'periodo')),
    elemento_id  VARCHAR(20),
    descricao    TEXT        NOT NULL,
    inicio       TIMESTAMPTZ NOT NULL,
    fim_previsto TIMESTAMPTZ,
    encerrada_em TIMESTAMPTZ,
    atraso_min   INTEGER     CHECK (atraso_min > 0),
    criada_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
    alterada_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((ambito = 'periodo') = (elemento_id IS NULL)),
    -- Só os atrasos têm minutos (e têm-nos sempre). Escrito como igualdade de booleanos
    -- porque um CHECK que dá NULL deixa passar a linha.
    CHECK ((tipo = 'atraso') = (atraso_min IS NOT NULL)),
    CHECK (fim_previsto IS NULL OR fim_previsto >= inicio)
);

-- Paragens não servidas por um desvio (A-08)

CREATE TABLE IF NOT EXISTS perturbacao_paragens_nao_servidas (
    perturbacao_id INTEGER     NOT NULL REFERENCES perturbacoes(id),
    paragem_id     VARCHAR(10) NOT NULL REFERENCES paragens(id),
    PRIMARY KEY (perturbacao_id, paragem_id)
);

-- Outbox dos eventos do Core (RF-13)

CREATE TABLE IF NOT EXISTS outbox (
    evento_id    UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
    tipo         VARCHAR(50) NOT NULL,
    conteudo     JSONB       NOT NULL,
    criado_em    TIMESTAMPTZ NOT NULL DEFAULT now(),
    publicado_em TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS outbox_por_publicar
    ON outbox (criado_em)
    WHERE publicado_em IS NULL;

